#!/usr/bin/env python3
"""Writes crates/sim/src/prefixes.rs from AD1C's cty.dat (https://www.country-files.com).

Usage: gen_prefixes.py cty.dat
"""
import pathlib, re, sys

REGION = ["NA", "SA", "EU", "AS", "OC", "AF"]  # order of Region::ALL
ENTITY = re.compile(
    r"^([^\s:][^:\n]*):\s*\d+:\s*\d+:\s*(\w\w):\s*[-\d.]+:\s*[-\d.]+:\s*[-\d.]+:\s*(\S+):\s*\n((?:\s+.*\n?)*?.*;)", re.M
)


def prefixes(body):
    """Plain prefixes, without single calls and zone overrides; the short ones if there are any."""
    items = [i.strip() for i in body.replace("\n", " ").rstrip(";").split(",")]
    plain = [re.sub(r"[(\[<{~].*", "", i) for i in items if not i.startswith("=")]
    plain = sorted({p for p in plain if p.isalnum()}, key=lambda p: (len(p), p))
    short = [p for p in plain if len(p) <= 3]
    return short or plain[:1]


def main():
    text = pathlib.Path(sys.argv[1]).read_text(encoding="latin-1").replace("\r", "")
    regions = {r: [] for r in REGION}
    for name, continent, main_prefix, body in ENTITY.findall(text):
        p = prefixes(body)
        # a leading * marks entities that only count for the WAE award
        if p and not main_prefix.startswith("*"):
            regions[continent].append((main_prefix.split("/")[0], name.strip(), p))
    out = [
        "//! Country prefixes per region, in the order of `Region::ALL`. Generated by",
        "//! tools/gen_prefixes.py from AD1C's cty.dat (country-files.com), do not edit.",
        "",
        "pub struct Country {",
        "    /// The usual prefix of the country.",
        "    pub main: &'static str,",
        "    pub name: &'static str,",
        "    pub prefixes: &'static [&'static str],",
        "}",
        "",
        "const fn c(main: &'static str, name: &'static str, prefixes: &'static [&'static str]) -> Country {",
        "    Country { main, name, prefixes }",
        "}",
        "",
        "pub const COUNTRIES: [&[Country]; 6] = [",
    ]
    for r in REGION:
        out += [f"    // {r}", "    &["]
        for main_prefix, name, p in regions[r]:
            q = ", ".join(f'"{x}"' for x in p)
            out.append(f'        c("{main_prefix}", "{name}", &[{q}]),')
        out.append("    ],")
    out.append("];")
    path = pathlib.Path(__file__).parent.parent / "crates/sim/src/prefixes.rs"
    path.write_text("\n".join(out) + "\n")
    print({r: len(v) for r, v in regions.items()}, sum(len(x[2]) for v in regions.values() for x in v))


main()
